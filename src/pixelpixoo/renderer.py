def draw_text(
    img: Image.Image,
    text: str,
    x: int,
    y: int,
    color: Color = WHITE,
    *,
    scale: int = 1,
    spacing: int = 1,
    tiny: bool = False,
) -> int:
    """Draw text. Returns width consumed in pixels."""
    draw = ImageDraw.Draw(img)
    cursor = x
    font = _FONT_3X5 if tiny else _FONT_5X7
    gw = (3 if tiny else 5) * scale
    for ch in text.upper():
        pattern = font.get(ch) or font.get("?") or _FONT_5X7["?"]
        for row, bits in enumerate(pattern):
            for col, bit in enumerate(bits):
                if bit != "#":
                    continue
                px = cursor + col * scale
                py = y + row * scale
                if scale == 1:
                    if 0 <= px < SIZE and 0 <= py < SIZE:
                        draw.point((px, py), fill=color)
                else:
                    draw.rectangle(
                        [px, py, px + scale - 1, py + scale - 1],
                        fill=color,
                    )
        cursor += gw + spacing
    return cursor - x - spacing if text else 0


def text_width(
    text: str, scale: int = 1, spacing: int = 1, *, tiny: bool = False
) -> int:
    if not text:
        return 0
    gw = (3 if tiny else 5) * scale
    return len(text) * (gw + spacing) - spacing


def draw_centered(
    img: Image.Image,
    text: str,
    y: int,
    color: Color = WHITE,
    *,
    scale: int = 1,
    tiny: bool = False,
    spacing: int = 1,
) -> None:
    w = text_width(text, scale=scale, spacing=spacing, tiny=tiny)
    x = max(0, (SIZE - w) // 2)
    draw_text(img, text, x, y, color, scale=scale, spacing=spacing, tiny=tiny)


def draw_label_bar(
    img: Image.Image,
    label: str,
    color: Color = CYAN,
    *,
    height: int = 9,
    tiny: bool = False,
) -> None:
    draw = ImageDraw.Draw(img)
    draw.rectangle([0, 0, SIZE - 1, max(6, height) - 1], fill=(20, 20, 28))
    y = 1 if height <= 8 else 2
    spacing = 0 if tiny else 1
    text = label.upper().strip()
    while text and text_width(text, tiny=tiny, spacing=spacing) > SIZE - 4:
        text = text[:-1]
    if text:
        draw_text(img, text, 2, y, color, tiny=tiny, spacing=spacing)


def fill_rect(
    img: Image.Image, x: int, y: int, w: int, h: int, color: Color
) -> None:
    ImageDraw.Draw(img).rectangle([x, y, x + w - 1, y + h - 1], fill=color)


def set_pixel(img: Image.Image, x: int, y: int, color: Color) -> None:
    if 0 <= x < SIZE and 0 <= y < SIZE:
        img.putpixel((x, y), color)


def error_frame(message: str = "ERR") -> Image.Image:
    img = new_canvas()
    draw_label_bar(img, "ERROR", RED)
    draw_centered(img, message[:10], 28, RED)
    return img


def fit_scale(text: str, max_width: int, *, prefer: int = 2, tiny: bool = False) -> int:
    for scale in range(prefer, 0, -1):
        if text_width(text, scale=scale, tiny=tiny) <= max_width:
            return scale
    return 1
